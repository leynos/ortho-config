//! The assembled candidate list and the decisions taken while assembling it.
//!
//! Split from `candidates` so the assembly logic and the value types it
//! produces each stay within the repository's 400-line module ceiling.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::Arc;

use crate::OrthoError;

use super::telemetry;
use super::{ConfigDiscovery, DiscoveryScope};

/// Normalizes a path according to Windows' case-insensitive comparison rules by
/// lowercasing ASCII code points on the original wide path representation and
/// replacing forward slashes with backslashes.
///
/// The key stays a raw `Vec<u16>`: converting to `String` would map every
/// unpaired surrogate to U+FFFD, so two distinct native paths could share a
/// key and deduplication would silently drop a valid candidate.
#[cfg(windows)]
fn windows_normalized_key(path: &Path) -> Vec<u16> {
    use std::os::windows::ffi::OsStrExt;

    path.as_os_str()
        .encode_wide()
        .map(|unit| match unit {
            65..=90 => unit + 32,
            47 => 92,
            _ => unit,
        })
        .collect()
}

impl ConfigDiscovery {
    /// Builds a native deduplication key without converting paths to UTF-8.
    pub(super) fn dedup_key(path: &Path) -> DedupKey {
        #[cfg(windows)]
        {
            windows_normalized_key(path)
        }

        #[cfg(not(windows))]
        {
            // The native `OsString`, not a lossy `String`: lossy conversion
            // maps every invalid byte to U+FFFD, so two distinct non-UTF-8
            // paths would collide and discovery would silently drop one.
            path.as_os_str().to_os_string()
        }
    }

    /// Exposes the production Windows key normalization to platform tests.
    #[cfg(all(test, windows))]
    pub(super) fn normalized_key(path: &Path) -> DedupKey {
        Self::dedup_key(path)
    }
}

/// Platform-shaped deduplication key.
///
/// Windows normalizes to the raw UTF-16 units (see `windows_normalized_key`);
/// every other platform keys on the native `OsString`. Both shapes preserve
/// paths that are not valid Unicode, so no two distinct paths share a key.
#[cfg(windows)]
pub(super) type DedupKey = Vec<u16>;
/// Native path representation used to distinguish non-UTF-8 paths off Windows.
///
/// Unlike a lossy `String`, an `OsString` keeps distinct native byte sequences
/// distinct during candidate deduplication.
#[cfg(not(windows))]
pub(super) type DedupKey = std::ffi::OsString;

/// One candidate path with the bounded label of the rung that produced it.
///
/// The label feeds candidate-failure telemetry. It is a `&'static str` drawn
/// from the closed `CANDIDATE_*` set in [`telemetry`], never a path, so the
/// module's no-values-in-events property survives the extra field.
///
/// `scopes` is a set rather than one label because a path can be generated by
/// more than one rung. `$XDG_CONFIG_HOME/demo/config.toml` is a user candidate,
/// and the same path is a project candidate whenever a project root is
/// `$XDG_CONFIG_HOME/demo` — a root is arbitrary, so nothing rules that out.
/// De-duplication keeps one entry, and recording only the first rung's scope
/// would make the path invisible to a request naming the other one.
pub(super) struct Candidate {
    /// Owned path attempted by discovery; the list order expresses preference.
    pub(super) path: PathBuf,
    /// Bounded source label used in telemetry instead of exposing the path.
    pub(super) source: &'static str,
    /// Whether absence or a load failure must be reported regardless of later
    /// candidates. Requiredness is the union of every rung that named the path.
    pub(super) required: bool,
    /// Every scope that generated this deduplicated path.
    scopes: Vec<DiscoveryScope>,
}

impl Candidate {
    /// Report whether this candidate belongs to `scope`.
    ///
    /// # Examples
    ///
    /// If one path was generated for both user and project scopes, querying
    /// either scope returns `true` after candidate deduplication.
    pub(super) fn in_scope(&self, scope: DiscoveryScope) -> bool {
        self.scopes.contains(&scope)
    }
}

/// One candidate to add, with the labels and policy that travel with it.
///
/// Grouping these fields keeps [`CandidateAccumulator::push_unique`] within the
/// repository's four-argument ceiling, and keeps the requiredness decision next
/// to the rung that made it instead of deriving it from the source label.
pub(super) struct CandidateSpec {
    /// Owned path attempted by discovery; insertion order is preference order.
    pub(super) path: PathBuf,
    /// Bounded source label used in telemetry instead of exposing the path.
    pub(super) source: &'static str,
    /// Whether absence or a load failure must be reported as fatal.
    pub(super) required: bool,
    /// Automatic discovery scope, or `None` for explicit and selector paths.
    pub(super) scope: Option<DiscoveryScope>,
}

/// Accumulates candidates while deduplicating per the platform's path rules.
#[derive(Default)]
pub(super) struct CandidateAccumulator {
    /// Unique candidates in first-seen preference order.
    pub(super) candidates: Vec<Candidate>,
    /// The index of each path's entry, so a later rung can record its scope and
    /// requiredness on the entry an earlier rung created instead of being
    /// refused outright.
    seen: HashMap<DedupKey, usize>,
}

impl CandidateAccumulator {
    /// Adds a required explicit candidate.
    ///
    /// A missing or failed required candidate is reported even when a later
    /// optional candidate loads.
    pub(super) fn push_required(&mut self, path: PathBuf, source: &'static str) -> bool {
        self.push_unique(CandidateSpec {
            path,
            source,
            required: true,
            scope: None,
        })
    }

    /// Adds an optional explicit candidate with no automatic scope.
    pub(super) fn push_optional(&mut self, path: PathBuf, source: &'static str) -> bool {
        self.push_unique(CandidateSpec {
            path,
            source,
            required: false,
            scope: None,
        })
    }

    /// Adds an optional candidate generated from an automatic base.
    pub(super) fn push_automatic(
        &mut self,
        path: PathBuf,
        source: &'static str,
        scope: DiscoveryScope,
    ) -> bool {
        self.push_unique(CandidateSpec {
            path,
            source,
            required: false,
            scope: Some(scope),
        })
    }

    /// Adds a new path once, recording later rung memberships on its entry.
    ///
    /// # Examples
    ///
    /// Pushing the same path for user and project scope returns `true` then
    /// `false`; the single stored candidate belongs to both scopes.
    pub(super) fn push_unique(&mut self, spec: CandidateSpec) -> bool {
        let CandidateSpec {
            path,
            source,
            required,
            scope,
        } = spec;
        if path.as_os_str().is_empty() {
            return false;
        }
        let key = ConfigDiscovery::dedup_key(&path);
        if let Some(index) = self.seen.get(&key).copied() {
            // The path is already listed, so it must not be listed twice. A
            // later rung can still add its scope and its requiredness: without
            // the scope the surviving entry would be reachable only from the
            // rung that happened to run first, and without the requiredness a
            // selector naming an optional explicit path could still fall back.
            self.record_membership(index, required, scope);
            return false;
        }
        self.seen.insert(key, self.candidates.len());
        self.candidates.push(Candidate {
            path,
            source,
            required,
            scopes: scope.into_iter().collect(),
        });
        true
    }

    /// Add a later rung's scope and requiredness to an existing entry.
    ///
    /// `requested` is the later rung's scope: `None` for a rung that has none,
    /// and `Some` for one whose path is already listed under a different scope.
    /// The entry keeps its path, its source, and its position — the candidate
    /// list is a preference order, so re-positioning it would change which
    /// location a scope's walk reaches first.
    ///
    /// Requiredness is promoted rather than replaced. If any rung says the path
    /// must exist, the candidate is required; a later optional rung cannot undo
    /// the stricter contract, and an earlier optional one cannot relax it.
    ///
    /// `index` is one this accumulator recorded itself, and `candidates` only
    /// ever grows, so the entry is always there. A miss does nothing rather
    /// than panicking: one is unreachable, and the other would be a panic path
    /// in a library.
    fn record_membership(
        &mut self,
        index: usize,
        required: bool,
        requested: Option<DiscoveryScope>,
    ) {
        let Some(candidate) = self.candidates.get_mut(index) else {
            return;
        };
        if required {
            candidate.required = true;
        }
        let Some(scope) = requested else {
            return;
        };
        if !candidate.scopes.contains(&scope) {
            candidate.scopes.push(scope);
        }
    }
}

/// The decisions made while assembling the candidate list.
///
/// Assembly records its decisions instead of emitting them so that
/// [`ConfigDiscovery::candidates`] stays a silent query; discovery operations
/// call [`CandidateDecisions::emit`] at their own boundary, which is where a
/// side effect belongs.
pub(super) struct CandidateDecisions {
    /// Bounded outcome describing how the configuration-path selector resolved.
    pub(super) selector: &'static str,
    /// Presence state for `XDG_CONFIG_HOME`: absent, empty, or present.
    pub(super) xdg_config_home: &'static str,
    /// Presence state for `XDG_CONFIG_DIRS`: absent, empty, or present.
    pub(super) xdg_dirs: &'static str,
    /// Bounded label describing how the final XDG locations were resolved.
    pub(super) xdg_resolution: &'static str,
    /// Which source, if any, supplied the home directory.
    pub(super) home: &'static str,
}

impl CandidateDecisions {
    /// Emit the recorded decisions as the usual discovery telemetry events.
    pub(super) fn emit(&self) {
        telemetry::selector_decision(self.selector);
        telemetry::xdg_decision(self.xdg_config_home, self.xdg_dirs, self.xdg_resolution);
        telemetry::home_decision(self.home);
    }
}

/// The assembled candidate list and the decisions taken while building it.
pub(super) struct CandidateSet {
    /// Ordered unique locations, from most-preferred to least-preferred.
    pub(super) candidates: Vec<Candidate>,
    /// Required failures produced while assembling the list.
    ///
    /// A relative selector that cannot be anchored has no path the loader may
    /// read, so it produces its required error here rather than a candidate.
    pub(super) assembly_errors: Vec<Arc<OrthoError>>,
    /// Decisions retained for emission by the load operation boundary.
    pub(super) decisions: CandidateDecisions,
}
